import json
from playwright.sync_api import sync_playwright
import os
DIST=os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),"dist")
OUT="file://"+os.path.join(DIST,"ritos-de-sangue.html")
errs=[]; log=[]
def ok(n,c,e=""): log.append(("OK    " if c else "FALHA ")+n+(" | "+str(e) if e!="" else ""))
with sync_playwright() as p:
    b=p.chromium.launch(); ctx=b.new_context(viewport={'width':1360,'height':2200}); pg=ctx.new_page()
    pg.on("pageerror", lambda e: errs.append("PAGEERROR "+str(e)))
    pg.route("**/*", lambda r: r.abort() if r.request.url.startswith("http") else r.continue_())
    pg.goto(OUT); pg.wait_for_timeout(1200)
    cnt=lambda: pg.inner_text('#deckCount')
    for t in ("gal","tier","tab","ctrl","radar","geral"):
        pg.click(f'[data-tab="{t}"]'); pg.wait_for_timeout(150)
    ok("seis abas sem exceção", not errs, errs)
    pg.click('[data-tab="tier"]'); pg.click('#v-tier .chip[data-card="henrika-domnathi"]'); pg.wait_for_timeout(200)
    p0=int(pg.inner_text('.dw-sum b')); pg.click('[data-act="step"][data-g="1"][data-d="1"]'); pg.check('[data-act="pet"]'); pg.wait_for_timeout(120)
    ok("stepper e pet", int(pg.inner_text('.dw-sum b'))==p0+2)
    pg.fill('[data-act="val"]','12.5'); pg.click('[data-act="set-tier"][data-v="D"]'); pg.wait_for_timeout(150)
    ok("valor não engole o clique seguinte", pg.locator('#v-tier .tier[data-t="D"] .chip').count()==1)
    pg.keyboard.press('Escape'); pg.click('[data-tab="geral"]'); pg.wait_for_timeout(200)
    ok("valor na tabela de relevância", '12,50' in pg.inner_text('#v-geral .rel-t'))
    pg.click('[data-tab="tier"]'); pg.wait_for_timeout(150)
    pg.drag_and_drop('#v-tier .chip[data-card="sol-ring"]','#v-tier [data-drop="tier:B"]'); pg.wait_for_timeout(250)
    ok("arrastar entre tiers", pg.locator('#v-tier .tier[data-t="B"] .chip[data-card="sol-ring"]').count()==1, pg.inner_text('#toast'))
    pg.click('[data-tab="ctrl"]'); pg.wait_for_timeout(150)
    pg.drag_and_drop('#v-ctrl .kan .chip[data-card="mind-stone"]','#v-ctrl [data-drop="rel:BAX"]'); pg.wait_for_timeout(250)
    ok("arrastar entre faixas", pg.locator('#v-ctrl .k-BAX .chip[data-card="mind-stone"]').count()==1, pg.inner_text('#toast'))
    pend=pg.inner_text('#v-ctrl .pend'); ok("pendências listam entradas sugeridas", 'Swords to Plowshares' in pend and 'Pitiless Plunderer' in pend)
    pg.click('[data-tab="radar"]'); pg.wait_for_timeout(150)
    ok("sugestões de saída", pg.eval_on_selector('#sel-swords-to-plowshares','e=>e.value')=="split-up" and pg.eval_on_selector('#sel-pitiless-plunderer','e=>e.value')=="henrika-domnathi" and pg.eval_on_selector('#sel-vault-of-the-archangel','e=>e.value')=="witch-s-cottage")
    for cid in ("emeritus-of-woe","saw-in-half","scheming-silvertongue","vein-ripper","cruel-celebrant","swords-to-plowshares","pitiless-plunderer"):
        pg.click(f'[data-act="swap"][data-id="{cid}"]'); pg.wait_for_timeout(120)
    ok("sete trocas sugeridas mantêm 100", cnt()=="100 cartas", cnt())
    ok("histórico com sete linhas", pg.locator('#v-radar .hist tbody tr').count()==7)
    pg.click('[data-tab="geral"]'); pg.wait_for_timeout(300)
    facts=pg.inner_text('#v-geral .facts').replace("\n"," "); read=pg.inner_text('#v-geral .read')
    log.append("       depois das 7 trocas: "+facts+" | placar "+pg.inner_text('#v-geral .score-big b'))
    log.append("       "+" / ".join(x.split('.')[0] for x in read.split("\n") if x.strip())[:330])
    ok("bloco de Saw in Half removido", pg.locator('#v-geral .saw').count()==0 and 'Saw in Half: regras' not in pg.inner_text('#v-geral'))
    pg.click('[data-tab="radar"]'); pg.fill('#nc-n','Carta de Teste'); pg.fill('#nc-c','{2}{W}{B}'); pg.click('[data-act="add-custom"]'); pg.wait_for_timeout(200)
    ok("carta nova no radar", pg.locator('#v-radar .cand h3:has-text("Carta de Teste")').count()==1)
    pg.click('[data-act="backup"]'); bk=pg.input_value('#bk-out'); j=json.loads(bk)
    ok("backup guarda trocas, datas e imagens", len(j['swaps'])==7 and j['swaps'][0].get('d') and j.get('img') is True)
    ok("decklist exportada com 95 linhas", len(pg.input_value('#bk-list').split('\n'))==95 and 'Emeritus of Woe' in pg.input_value('#bk-list'))
    pg.click('[data-act="reset-all"]'); pg.click('[data-act="reset-all"]'); pg.wait_for_timeout(200)
    ok("recomeçar", cnt()=="100 cartas" and pg.locator('#v-radar .hist').count()==0)
    pg.click('[data-act="backup"]'); pg.fill('#bk-in',bk); pg.click('[data-act="import"]'); pg.wait_for_timeout(250)
    ok("restaurar backup", pg.locator('#v-radar .hist tbody tr').count()==7 and cnt()=="100 cartas")
    pg.click('[data-act="backup"]'); pg.click('[data-act="reset-all"]'); pg.click('[data-act="reset-all"]'); pg.wait_for_timeout(150)
    b.close()
print("\n".join(log)); print("erros:", errs)
